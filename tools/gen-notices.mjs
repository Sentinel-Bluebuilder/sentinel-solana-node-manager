// ─── Third-party notices ───
// Writes THIRD-PARTY-NOTICES.md: every production npm package the app ships, with its licence and
// repository. Packages without a `license` field (buildcheck, cpu-features, ssh2) are read from their
// LICENSE file. Run after any dependency change:  node tools/gen-notices.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT = path.join(ROOT, 'THIRD-PARTY-NOTICES.md');

// ─── Collect the production tree ───
const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], { cwd: ROOT, maxBuffer: 64 * 1024 * 1024, shell: process.platform === 'win32' }).toString(),
);

const seen = new Map();
function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (!d.version || !d.path) continue;
    const key = `${name}@${d.version}`;
    if (!seen.has(key)) seen.set(key, { name, version: d.version, dir: d.path });
    walk(d.dependencies);
  }
}
walk(tree.dependencies);

// ─── Licence of one package ───
function licenceFileGuess(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  if (!file) return { id: 'UNKNOWN', file: undefined };
  const text = readFileSync(path.join(dir, file), 'utf8');
  const id = /MIT License|Permission is hereby granted, free of charge/i.test(text)
    ? 'MIT'
    : /Apache License/i.test(text)
      ? 'Apache-2.0'
      : /ISC License|Permission to use, copy, modify, and\/or distribute/i.test(text)
        ? 'ISC'
        : /BSD/i.test(text)
          ? 'BSD (see file)'
          : 'see file';
  return { id, file };
}

const rows = [];
// Font packages (OFL-1.1) need their full licence text in the notices, not only a row.
const fullTexts = [];
for (const { name, version, dir } of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  if (!existsSync(path.join(dir, 'package.json'))) {
    console.warn(`skipped ${name}@${version}: no package.json at ${dir}`);
    continue;
  }
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const declared = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type;
  const guess = licenceFileGuess(dir);
  const licence = declared ?? `${guess.id} (no license field; from ${guess.file ?? 'no licence file'})`;
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  rows.push(`| ${name} | ${version} | ${licence} | ${repo.replace(/^git\+/, '').replace(/\.git$/, '')} |`);
  if (/OFL/i.test(licence)) {
    if (!guess.file) throw new Error(`${name}@${version} is OFL but ships no licence file`);
    const fence = '```';
    fullTexts.push([`## ${name} ${version} (${licence})`, '', fence, readFileSync(path.join(dir, guess.file), 'utf8').trim(), fence, ''].join('\n'));
  }
}

writeFileSync(
  OUT,
  [
    '# Third-party notices',
    '',
    'npm packages shipped with the app (production dependencies). Each package keeps its own licence file',
    'inside the packaged `node_modules`. The node image\'s components are listed in the image itself at',
    '`/usr/share/licenses/node-image/NOTICES` (see `docker/*.Dockerfile`).',
    '',
    'Generated by `node tools/gen-notices.mjs`; do not edit by hand.',
    '',
    '| Package | Version | Licence | Source |',
    '|---|---|---|---|',
    ...rows,
    ...(fullTexts.length ? ['', '# Full licence texts', '', ...fullTexts] : []),
    '',
  ].join('\n'),
);
console.log(`wrote ${rows.length} packages to ${path.relative(ROOT, OUT)}`);
